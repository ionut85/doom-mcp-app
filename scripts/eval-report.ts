// Builds docs/EVAL.md from docs/eval/results.jsonl (written by scripts/eval.ts).
// Usage: pnpm eval:report
import fs from "node:fs";
import path from "node:path";

const ROOT = path.resolve(import.meta.dirname, "..");
const rows = fs
  .readFileSync(path.join(ROOT, "docs/eval/results.jsonl"), "utf8")
  .split("\n")
  .filter(Boolean)
  .map((l) => JSON.parse(l));

const mean = (xs: number[]) => xs.reduce((a, b) => a + b, 0) / Math.max(xs.length, 1);
const sd = (xs: number[]) => {
  const m = mean(xs);
  return Math.sqrt(mean(xs.map((x) => (x - m) ** 2)));
};
const fmt = (xs: number[], d = 1) => (xs.length > 1 ? `${mean(xs).toFixed(d)} ± ${sd(xs).toFixed(d)}` : mean(xs).toFixed(d));

const groups = new Map<string, any[]>();
for (const r of rows) {
  const who = r.policy === "claude" ? `${r.model} (${r.effort})` : "scripted bot";
  const k = [r.label || "-", who, r.perception, r.skill].join("|");
  if (!groups.has(k)) groups.set(k, []);
  groups.get(k)!.push(r);
}

const table = [
  "| Label | Player | Perception | Skill | Runs | Kills | Damage taken | Deaths | Exit | Cells explored | Actions | Tokens/action | Cost/run |",
  "|---|---|---|---|---|---|---|---|---|---|---|---|---|",
];
for (const [k, rs] of [...groups.entries()].sort()) {
  const [label, who, perception, skill] = k.split("|");
  const exits = rs.filter((r) => r.exit_reached).length;
  const claude = rs[0].policy === "claude";
  const tpa = claude ? Math.round(mean(rs.map((r) => r.tokens_per_action))).toLocaleString("en-US") : "-";
  const cost = claude ? "$" + mean(rs.map((r) => r.cost_usd)).toFixed(2) : "-";
  table.push(
    [
      "",
      label,
      who,
      perception,
      skill,
      rs.length,
      `${fmt(rs.map((r) => r.kills))} / ${rs[0].total_kills}`,
      fmt(rs.map((r) => r.damage_taken), 0),
      fmt(rs.map((r) => r.deaths)),
      `${exits}/${rs.length}`,
      fmt(rs.map((r) => r.cells_explored), 0),
      fmt(rs.map((r) => r.actions), 0),
      tpa,
      cost,
      "",
    ].join(" | ").trim(),
  );
}
const total = rows.reduce((a, r) => a + (r.cost_usd ?? 0), 0);

const md = [
  "# Evaluation: Claude playing E1M1",
  "",
  `Generated by \`pnpm eval:report\` from \`docs/eval/results.jsonl\` (${rows.length} runs, total model cost $${total.toFixed(2)}).`,
  "",
  "Each run starts a fresh game of Freedoom E1M1 through the live MCP server. The player gets up to 50 tool calls. A run ends when the budget is used up, the level is completed, or the model stops after three \"keep playing\" nudges.",
  "",
  "- **Kills** are out of the map's monster count for that skill.",
  "- **Damage taken** is health plus armor lost, not counting respawns.",
  "- **Cells explored** counts distinct 64×64-unit map cells the player stood in after an action.",
  "- **Tokens/action** counts all input (cached and uncached) and output tokens per tool call.",
  "- **Cost** uses list prices, with prompt caching on.",
  "",
  "Values are mean ± standard deviation across runs.",
  "",
  ...table,
  "",
  "## Notes",
  "",
  "See `docs/PLAN.md` (Phase 5 results) for the setup, the failure modes found in the transcripts, and what changed between labels.",
  "",
].join("\n");
fs.writeFileSync(path.join(ROOT, "docs/EVAL.md"), md);
console.log(md);
